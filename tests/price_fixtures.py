def historical_agile_prices(day_start, values_pence):
    return [
        {
            'valid_from': day_start + timedelta(minutes=30 * index),
            'valid_to': day_start + timedelta(minutes=30 * (index + 1)),
            'price_gbp': value / 100,
        }
        for index, value in enumerate(values_pence)
    ]


def historical_agile_rate_records(day_start, values_pence):
    return [
        {
            "valid_from": (day_start + timedelta(minutes=30 * index)).isoformat().replace("+00:00", "Z"),
            "valid_to": (day_start + timedelta(minutes=30 * (index + 1))).isoformat().replace("+00:00", "Z"),
            "value_inc_vat": value,
        }
        for index, value in enumerate(values_pence)
    ]
